def is_placeholder(category):
    current = (category.description or '').strip()
    return not current or current.lower() == (category.title or '').strip().lower()


class Command(BaseCommand):
    help = 'Fill Category.description for catalog categories that have no real SEO text'

    def add_arguments(self, parser):
        parser.add_argument(
            '--force',
            action='store_true',
            help='Overwrite descriptions that already contain text (default: only empty/title placeholders)',
        )
        parser.add_argument(
            '--dry-run',
            action='store_true',
            help='Show what would change without writing',
        )
        parser.add_argument(
            '--slugs',
            default='',
            help='Comma-separated category slugs to limit the run',
        )
        parser.add_argument(
            '--no-products',
            action='store_true',
            help='Do not append the list of products from the category',
        )
        parser.add_argument(
            '--max-items',
            type=int,
            default=12,
            help='Maximum products listed per category (default: 12, 0 = no limit)',
        )

    def get_slug_filter(self, value):
        return [item.strip() for item in value.split(',') if item.strip()]

    def product_url(self, product):
        main_category = product.category.main_category
        if not main_category:
            return None
        return '/catalog/%s/%s/%s/' % (main_category.slug, product.category.slug, product.slug)

    def build_products_block(self, category, max_items):
        products = Product.objects.filter(category=category, is_visible=True)
        if max_items > 0:
            products = products[:max_items]

        items = []
        for product in products:
            title = escape(product.title)
            article = (product.article or '').strip()
            label = '%s — %s' % (escape(article), title) if article else title
            url = self.product_url(product)
            items.append('<li><a href="%s">%s</a></li>' % (url, label) if url else '<li>%s</li>' % label)

        if not items:
            return ''
        return '<p>В наличии:</p>\n<ul>\n%s\n</ul>' % '\n'.join(items)

    def build_description(self, data, category, with_products, max_items):
        blocks = ['<p>%s</p>' % paragraph for paragraph in data['paragraphs']]

        if with_products and data.get('list_heading'):
            block = self.build_products_block(category, max_items)
            if block:
                blocks.append(block)

        if data.get('outro'):
            blocks.append('<p>%s <a href="/contacts/">Написать в отдел продаж</a></p>' % data['outro'])

        return '\n'.join(blocks)

    def handle(self, *args, **options):
        force = options['force']
        dry_run = options['dry_run']
        with_products = not options['no_products']
        max_items = options['max_items']
        slug_filter = self.get_slug_filter(options['slugs'])

        queryset = Category.objects.select_related('main_category').all()
        if slug_filter:
            queryset = queryset.filter(slug__in=slug_filter)

        filled = []
        overwritten = []
        skipped = []
        unknown = []

        for category in queryset:
            data = DESCRIPTIONS.get(category.slug)
            if not data:
                unknown.append(category.slug)
                continue

            if not force and not is_placeholder(category):
                skipped.append(category.slug)
                continue

            description = self.build_description(data, category, with_products, max_items)
            Category.objects.filter(pk=category.pk).update(description=description)

            if force and not is_placeholder(category):
                overwritten.append(category.slug)
            else:
                filled.append(category.slug)

        if dry_run:
            self.stdout.write(self.style.WARNING('DRY RUN — no changes written'))
        for slug in filled:
            self.stdout.write(self.style.SUCCESS('  + filled:    %s' % slug))
        for slug in overwritten:
            self.stdout.write(self.style.WARNING('  ~ rewritten: %s' % slug))
        for slug in skipped:
            self.stdout.write('  - skipped:   %s (has own text, use --force)' % slug)
        for slug in unknown:
            self.stdout.write('  ! no text:   %s (add to DESCRIPTIONS if needed)' % slug)

        self.stdout.write('')
        self.stdout.write(self.style.SUCCESS(
            'Done: %d filled, %d rewritten, %d skipped, %d without text' % (
                len(filled), len(overwritten), len(skipped), len(unknown)
            )
        ))
